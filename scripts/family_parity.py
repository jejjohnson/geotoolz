"""Family name parity between geoops and xrops (geostack PL-D, gate D1).

geoops and xrops are organised in families (``geoops.geom``, ``xrops.geom``,
…). A family name used by both must mean the same job on either lane, so a
user finds reprojection, rasterizing and masking in the same place on both
sides. ``SAME_JOB`` records that job for every shared name; the check fails
when a shared family has no entry, when an entry names a family that is no
longer shared, or when ``docs/api/families.md`` is stale.

    uv run python scripts/family_parity.py            # rewrite the table
    uv run python scripts/family_parity.py --check    # fail if stale or broken
"""

from __future__ import annotations

import importlib
import pkgutil
import sys
from collections.abc import Mapping
from pathlib import Path

import cyclopts
from loguru import logger


ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "docs" / "api" / "families.md"
PACKAGES = ("geoops", "xrops")

#: the job every family name shared by geoops and xrops means on both lanes
SAME_JOB: dict[str, str] = {
    "geom": "geometry: CRS and reprojection, subsetting and cropping, mosaics,"
    " rasterize and vectorize (geoops also keeps its gradient operators here;"
    " xrops's are `xrops.grad`)",
    "learn": "scikit-learn estimators fitted and applied on the lane's carrier"
    " (GeoArray; DataArray, Dataset and DataTree)",
    "mask": "masks: land, ocean and country masks, region masks, and applying a mask",
    "viz": "visualization: colormaps, composites and display panels",
}

app = cyclopts.App(help=__doc__)


def families(package: str) -> dict[str, str]:
    """The public families (subpackages) of ``package``, with their summary line."""
    module = importlib.import_module(package)
    out = {}
    for info in pkgutil.iter_modules(module.__path__):
        if not info.ispkg or info.name.startswith("_"):
            continue
        doc = importlib.import_module(f"{package}.{info.name}").__doc__ or ""
        line = doc.strip().splitlines()[0].rstrip(".") if doc.strip() else ""
        out[info.name] = line.replace("``", "`")  # reST literals as Markdown
    return out


def problems(
    geo: Mapping[str, str], xr: Mapping[str, str], same_job: Mapping[str, str]
) -> list[str]:
    """What breaks the parity rule: a shared name without a job, a stale entry."""
    shared = set(geo) & set(xr)
    out = [
        f"'{name}' is a family of both geoops and xrops: say the job it means on"
        " both lanes in SAME_JOB, or rename one of them"
        for name in sorted(shared - set(same_job))
    ]
    out += [
        f"'{name}' is in SAME_JOB but is no longer a family of both: remove it"
        for name in sorted(set(same_job) - shared)
    ]
    return out


def table(
    geo: Mapping[str, str], xr: Mapping[str, str], same_job: Mapping[str, str]
) -> str:
    """The checked-in page: every family of either package, shared ones first."""
    lines = [
        "# Families of geoops and xrops",
        "",
        "<!-- Generated by scripts/family_parity.py; do not edit by hand. -->",
        "",
        "geoops and xrops are organised in families. A family name used by both"
        " means the same job on either lane (geostack gate D1); the shared ones"
        " are listed first, with that job.",
        "",
        "| Family | Shared job | geoops | xrops |",
        "| --- | --- | --- | --- |",
    ]
    shared = sorted(set(geo) & set(xr))
    rest = sorted((set(geo) | set(xr)) - set(shared))
    for name in [*shared, *rest]:
        lines.append(
            f"| `{name}` | {same_job.get(name, '')} | {geo.get(name, '—') or '—'}"
            f" | {xr.get(name, '—') or '—'} |"
        )
    return "\n".join(lines) + "\n"


@app.default
def main(*, check: bool = False) -> None:
    """Write ``docs/api/families.md``, or with ``--check`` fail if it is stale.

    Args:
        check: Verify instead of writing; exit 1 on a parity problem or a
            stale page.
    """
    geo, xr = families("geoops"), families("xrops")
    found = problems(geo, xr, SAME_JOB)
    for problem in found:
        logger.error(problem)
    text = table(geo, xr, SAME_JOB)
    if check:
        stale = not PAGE.exists() or PAGE.read_text(encoding="utf-8") != text
        if stale:
            logger.error(
                f"{PAGE.relative_to(ROOT)} is stale: run {Path(__file__).name}"
            )
        if found or stale:
            sys.exit(1)
        logger.info(f"{len(set(geo) & set(xr))} shared families, all the same job")
        return
    if found:
        sys.exit(1)
    PAGE.write_text(text, encoding="utf-8")
    logger.info(f"wrote {PAGE.relative_to(ROOT)}")


if __name__ == "__main__":
    app()
