"""geoops — composable Operator library for remote sensing.

The composition core (`Operator`, `Sequential`, `Graph`, …) lives in
the carrier-agnostic [`pipekit`](https://github.com/jejjohnson/pipekit)
framework — `geoops` re-exports the common names at the top level and
adds the per-domain operator families (`radiometry`, `indices`, `qa`,
`mask`, …) on top.

    import geoops as gz
    pipe = gz.Sequential([gz.Tap(print), gz.Identity()])

Re-export policy: every public **Operator class** of every family
(including subnamespaces such as ``geom.coregister``) plus the ``SCL``
class sets and ``SENSOR_QA_REGISTRY`` is available at the top level;
the **Tier-A numpy primitives** (``ndvi``, ``apply_mask``,
``percentile_clip``, ...) and other helpers live in their submodules
only. Each public name has exactly one home family, so every top-level
name is unambiguous. ``tests/test_geotoolz.py::test_public_operators_exported``
enforces this; the only exceptions are:

- ``augment.Compose`` (a probability-gated ``Sequential`` of
  augmentations): at the top level it would sit next to pipekit's
  right-to-left ``compose`` and read as a generic composer, so it is
  spelled ``gz.augment.Compose``.
- ``io.SourceOperator`` / ``io.SinkOperator``: abstract base classes
  for writing new readers / writers (they have no ``_apply``), not
  pipeline steps, and ``SinkOperator`` would sit next to pipekit's
  ``Sink``. Subclass them from ``gz.io``.
- ``patch_ops``: an optional extra (below); ``import geoops`` must not
  require geopatcher, so its operators are only reachable as
  ``gz.patch_ops.*``.

The four-axis Patcher framework lives in the
[`geotoolz-patcher`](https://github.com/jejjohnson/geotoolz/tree/main/packages/geotoolz-patcher)
workspace package (import name `geopatcher`). Install
the optional `[patch]` extra (``pip install 'geotoolz-ops[patch]'``) to pull
it in and use ``geoops.patch_ops`` for the Operator-graph bridge:

    import geopatcher as gp
    from geoops import Sequential
    from geoops.patch_ops import GridSampler, ApplyToChips, MergePatches

Product readers (``ProductReader`` and the per-sensor / per-provider
subpackages) live in the
[`geotoolz-products`](https://github.com/jejjohnson/geotoolz/tree/main/packages/geotoolz-products)
workspace package (import name `geoproducts`); their output is a
`GeoArray` every operator here accepts.
"""

