def test_every_public_name_moved() -> None:
    assert set(OLD_ALL) <= set(xrproducts.__all__)
    assert set(OLD_TYPES_ALL) <= set(xrproducts.types.__all__)
    for name in OLD_ALL:
        assert hasattr(xrproducts, name), name
    for name in OLD_TYPES_ALL:
        assert hasattr(xrproducts.types, name), name


def test_the_old_import_name_is_gone() -> None:
    assert importlib.util.find_spec("xrreader") is None
